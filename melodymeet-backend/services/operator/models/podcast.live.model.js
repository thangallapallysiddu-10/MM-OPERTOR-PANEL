const { DataTypes } = require('sequelize');
const sequelize = require('../config/db.config');

/**
 * PodcastLiveSession — tracks each live broadcast started from the Podcast Studio.
 * Each session is identified by a unique roomId generated on the frontend.
 * This model is separate from the RJ-Studio LiveSession (activity.model.js)
 * because podcast live sessions have different lifecycle and metadata needs.
 */
const PodcastLiveSession = sequelize.define('PodcastLiveSession', {
  id: {
    type: DataTypes.INTEGER,
    autoIncrement: true,
    primaryKey: true,
  },

  title: {
    type: DataTypes.STRING,
    allowNull: false,
    validate: { notEmpty: true, len: [1, 180] },
  },

  description: {
    type: DataTypes.TEXT,
    allowNull: true,
  },

  // Short alphanumeric room identifier generated by the frontend
  roomId: {
    type: DataTypes.STRING,
    allowNull: false,
    validate: { notEmpty: true },
  },

  // Full shareable URL including the roomId
  roomLink: {
    type: DataTypes.STRING,
    allowNull: true,
  },

  host: {
    type: DataTypes.STRING,
    allowNull: true,
    defaultValue: 'Operator',
    validate: { len: [0, 120] },
  },

  status: {
    type: DataTypes.ENUM('live', 'ended'),
    defaultValue: 'live',
  },

  peakViewers: {
    type: DataTypes.INTEGER,
    defaultValue: 0,
    validate: { min: 0 },
  },

  lastViewerCount: {
    type: DataTypes.INTEGER,
    defaultValue: 0,
    validate: { min: 0 },
  },

  startedAt: {
    type: DataTypes.DATE,
    defaultValue: DataTypes.NOW,
  },

  // Null until the stream ends
  endedAt: {
    type: DataTypes.DATE,
    allowNull: true,
  },
}, {
  timestamps: true,
  indexes: [
    { fields: ['status'] },
    // Fast lookup by roomId (used on every stop/guest-join call)
    { fields: ['roomId'] },
    { fields: ['startedAt'] },
  ],
});

module.exports = PodcastLiveSession;
